create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_role public.user_role := 'operator';
begin
  if not exists(select 1 from public.profiles where role = 'admin') then
    v_role := 'admin';
  end if;

  insert into public.profiles (id, email, role)
  values (new.id, new.email, v_role)
  on conflict (id) do update
  set email = excluded.email;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row
execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create or replace function public.calculate_amount_cop(
  p_base_minutes integer,
  p_base_price_cop integer,
  p_used_minutes integer
)
returns integer
language sql
immutable
as $$
  select ceil(
    (greatest(p_base_price_cop, 1)::numeric / greatest(p_base_minutes, 1)::numeric)
    * greatest(p_used_minutes, 0)::numeric
  )::integer;
$$;

create or replace function public.start_session(
  p_atv_id uuid,
  p_duration_minutes integer
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_atv public.atvs%rowtype;
  v_duration integer;
  v_session_id uuid;
begin
  if auth.uid() is null then
    raise exception 'No autenticado';
  end if;

  if p_duration_minutes is null or p_duration_minutes <= 0 then
    raise exception 'La duracion debe ser mayor que cero';
  end if;

  select * into v_atv
  from public.atvs
  where id = p_atv_id and active = true;

  if not found then
    raise exception 'La cuatrimoto no existe o esta inactiva';
  end if;

  if exists (
    select 1
    from public.sessions
    where atv_id = p_atv_id and status = 'active'
  ) then
    raise exception 'La cuatrimoto ya tiene una sesion activa';
  end if;

  v_duration := greatest(1, p_duration_minutes);

  insert into public.sessions (
    atv_id,
    started_by,
    started_at,
    target_end_at,
    status
  )
  values (
    p_atv_id,
    auth.uid(),
    timezone('utc', now()),
    timezone('utc', now()) + make_interval(mins => v_duration),
    'active'
  )
  returning id into v_session_id;

  return v_session_id;
end;
$$;

create or replace function public.stop_session(
  p_session_id uuid
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_session public.sessions%rowtype;
  v_atv public.atvs%rowtype;
  v_minutes integer;
  v_amount integer;
begin
  if auth.uid() is null then
    raise exception 'No autenticado';
  end if;

  select * into v_session
  from public.sessions
  where id = p_session_id;

  if not found then
    raise exception 'Sesion no encontrada';
  end if;

  if v_session.status <> 'active' then
    return v_session.id;
  end if;

  select * into v_atv
  from public.atvs
  where id = v_session.atv_id;

  v_minutes := ceil(extract(epoch from (timezone('utc', now()) - v_session.started_at)) / 60.0)::integer;
  v_amount := public.calculate_amount_cop(v_atv.base_minutes, v_atv.base_price_cop, v_minutes);

  update public.sessions
  set
    status = 'completed',
    ended_at = timezone('utc', now()),
    minutes_billed = v_minutes,
    amount_cop = v_amount,
    updated_at = timezone('utc', now())
  where id = v_session.id;

  return v_session.id;
end;
$$;

create or replace function public.extend_session(
  p_session_id uuid,
  p_extra_minutes integer
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_session public.sessions%rowtype;
begin
  if auth.uid() is null then
    raise exception 'No autenticado';
  end if;

  if p_extra_minutes is null or p_extra_minutes <= 0 then
    raise exception 'Los minutos extra deben ser mayores que cero';
  end if;

  select * into v_session
  from public.sessions
  where id = p_session_id;

  if not found then
    raise exception 'Sesion no encontrada';
  end if;

  if v_session.status <> 'active' then
    raise exception 'Solo se puede extender una sesion activa';
  end if;

  update public.sessions
  set target_end_at = target_end_at + make_interval(mins => p_extra_minutes)
  where id = v_session.id;

  return v_session.id;
end;
$$;

create or replace function public.refresh_expired_sessions()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_now timestamptz := timezone('utc', now());
  v_count integer := 0;
begin
  update public.sessions
  set
    status = 'completed',
    ended_at = v_now,
    minutes_billed = ceil(extract(epoch from (v_now - started_at)) / 60.0)::integer,
    amount_cop = public.calculate_amount_cop(
      atvs.base_minutes,
      atvs.base_price_cop,
      ceil(extract(epoch from (v_now - started_at)) / 60.0)::integer
    ),
    updated_at = v_now
  from public.atvs
  where
    public.sessions.atv_id = public.atvs.id
    and public.sessions.status = 'active'
    and public.sessions.target_end_at <= v_now;

  get diagnostics v_count = row_count;

  insert into public.notification_queue (session_id, kind, payload)
  select
    s.id,
    'session_expired',
    jsonb_build_object('session_id', s.id, 'atv_id', s.atv_id, 'target_end_at', s.target_end_at)
  from public.sessions s
  where s.status = 'completed'
    and s.ended_at = v_now
  on conflict (session_id) do nothing;

  return v_count;
end;
$$;

create or replace view public.vw_finance_by_atv_today
with (security_invoker = true)
as
select
  a.id as atv_id,
  a.name as atv_name,
  count(s.id)::integer as session_count,
  coalesce(sum(s.minutes_billed), 0)::integer as minutes_total,
  coalesce(sum(s.amount_cop), 0)::integer as amount_total_cop
from public.atvs a
left join public.sessions s
  on s.atv_id = a.id
  and s.status = 'completed'
  and timezone('America/Bogota', s.ended_at)::date = timezone('America/Bogota', now())::date
group by a.id, a.name;

create or replace view public.vw_finance_total_today
with (security_invoker = true)
as
select
  count(s.id)::integer as session_count,
  coalesce(sum(s.minutes_billed), 0)::integer as minutes_total,
  coalesce(sum(s.amount_cop), 0)::integer as amount_total_cop
from public.sessions s
where
  s.status = 'completed'
  and timezone('America/Bogota', s.ended_at)::date = timezone('America/Bogota', now())::date;

