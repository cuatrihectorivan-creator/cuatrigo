create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role public.user_role not null default 'operator',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.atvs (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  plate text unique,
  active boolean not null default true,
  base_minutes integer not null default 10 check (base_minutes > 0),
  base_price_cop integer not null default 10000 check (base_price_cop > 0),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.sessions (
  id uuid primary key default gen_random_uuid(),
  atv_id uuid not null references public.atvs(id) on delete restrict,
  started_by uuid not null references auth.users(id) on delete restrict,
  started_at timestamptz not null default timezone('utc', now()),
  target_end_at timestamptz not null,
  ended_at timestamptz,
  status public.session_status not null default 'active',
  minutes_billed integer check (minutes_billed is null or minutes_billed >= 0),
  amount_cop integer check (amount_cop is null or amount_cop >= 0),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null unique references public.sessions(id) on delete cascade,
  amount_cop integer not null check (amount_cop > 0),
  method text not null check (method in ('cash', 'transfer', 'card', 'other')),
  paid_at timestamptz not null default timezone('utc', now()),
  recorded_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.notification_queue (
  id bigint generated by default as identity primary key,
  session_id uuid not null unique references public.sessions(id) on delete cascade,
  kind text not null,
  payload jsonb not null,
  delivered_at timestamptz,
  created_at timestamptz not null default timezone('utc', now())
);

